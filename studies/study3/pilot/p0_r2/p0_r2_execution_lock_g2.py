def validate(lock: dict, schema_document=None) -> dict:
    """Validate a lock with the v2 schema walker, imported not restated."""
    schema_document = schema_document if schema_document is not None \
        else schema()
    errors = V2._validate(lock, schema_document)  # noqa: SLF001 - shared walker
    if errors:
        raise LockDefect("; ".join(errors[:8]))
    payload = dict(lock)
    declared = (payload.get("self") or {}).get("sha256")
    recomputed = dict(payload)
    recomputed["self"] = dict(payload["self"])
    recomputed["self"]["sha256"] = None
    if declared != _sha256(canonical_bytes(recomputed)):
        raise LockDefect("the lock does not bind its own canonical bytes")
    NS.assert_disjoint_from_generation1([
        (lock.get("namespace") or {}).get("live_replay_attempt_id"),
        (lock.get("namespace") or {}).get("pilot_attempt_id"),
        (lock.get("namespace") or {}).get("live_blob_prefix"),
        (lock.get("namespace") or {}).get("pilot_blob_prefix"),
    ])
    if (lock.get("image") or {}).get("digest") == \
            GENERATION1_TERMINAL["image_digest"]:
        raise LockDefect(
            "the generation-2 image digest equals the generation-1 digest")
    return {
        "schema_version": "study3-p0-r2-execution-lock-validation-g2",
        "stage": STAGE,
        "generation": GENERATION,
        "outcome": "LOCK_VALID",
        "lock_sha256": declared,
        "errors": 0,
        "model_operations_performed": 0,
    }


