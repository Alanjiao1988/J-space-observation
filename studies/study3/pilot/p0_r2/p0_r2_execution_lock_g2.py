def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--identity", action="store_true")
    mode.add_argument("--schema", action="store_true")
    mode.add_argument("--build", action="store_true")
    mode.add_argument("--validate", action="store_true")
    parser.add_argument("--root")
    parser.add_argument("--inputs")
    parser.add_argument("--lock-file")
    parser.add_argument("--schema-file")
    parser.add_argument("--out")
    args = parser.parse_args(argv)

    if args.identity:
        print(json.dumps(implementation_identity(), indent=2, sort_keys=True))
        return 0

    try:
        if args.schema:
            document = schema()
        elif args.build:
            if not args.inputs:
                raise LockDefect("--build requires --inputs")
            inputs = json.loads(Path(args.inputs).read_bytes().decode("utf-8"))
            document = build(args.root, inputs=inputs)
        else:
            if not args.lock_file:
                raise LockDefect("--validate requires --lock-file")
            lock = json.loads(Path(args.lock_file).read_bytes().decode("utf-8"))
            schema_document = None
            if args.schema_file:
                schema_document = json.loads(
                    Path(args.schema_file).read_bytes().decode("utf-8"))
            document = validate(lock, schema_document)
    except (LockDefect, NS.NamespaceDefect, ValueError) as exc:
        print("P0_R2_G2_EXECUTION_LOCK_REFUSED=1 %s" % exc, file=sys.stderr)
        return 3

    payload = canonical_bytes(document)
    if args.out:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_bytes(payload)
    print(payload.decode("utf-8"), end="")
    if args.validate:
        print("P0_R2_G2_EXECUTION_LOCK_VALID=1")
    return 0


if __name__ == "__main__":
    sys.exit(main())
