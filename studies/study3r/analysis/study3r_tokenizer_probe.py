def equivalence_tuple(probe, arm_id: str):
    """The ``(bytes, token IDs, common prefix, discriminant position)`` tuple."""
    arm = probe["arms"][arm_id]
    return {
        "bytes": arm["prompt"]["utf8_sha256"],
        "token_ids": arm["prompt"]["token_ids"],
        "common_prefix": arm["d0_common_prefix_token_ids"],
        "discriminant_position": arm["d0_discriminant_position"],
        "answer_surface_token_ids": {
            label: probe["e0"]["legal_answer_surfaces"][label]["token_ids"]
            for label in tasks.LABELS
        },
    }


def build_equivalence(probes):
    reference = probes[0]
    strata = {}
    comparisons = []
    for arm_id in (RAW_ARM_ID, CHAT_ARM_ID):
        reference_tuple = equivalence_tuple(reference, arm_id)
        for probe in probes:
            candidate = equivalence_tuple(probe, arm_id)
            differing = sorted(key for key in reference_tuple
                               if reference_tuple[key] != candidate[key])
            comparisons.append({
                "arm_id": arm_id,
                "reference_role": reference["role"],
                "role": probe["role"],
                "repository_id": probe["repository_id"],
                "immutable_revision": probe["immutable_revision"],
                "identical_to_reference": not differing,
                "differing_tuple_elements": differing,
            })
    for probe in probes:
        signature = hashlib.sha256(json.dumps(
            {arm_id: equivalence_tuple(probe, arm_id)
             for arm_id in (RAW_ARM_ID, CHAT_ARM_ID)},
            sort_keys=True).encode("utf-8")).hexdigest()
        strata.setdefault(signature, []).append(probe["role"])
    stratum_ids = {}
    for index, signature in enumerate(sorted(strata), start=1):
        stratum_ids[signature] = "STRATUM_%02d" % index
    return {
        "reference_role": reference["role"],
        "verified_tuple_elements": ["bytes", "token_ids", "common_prefix",
                                    "discriminant_position",
                                    "answer_surface_token_ids"],
        "comparisons": comparisons,
        "strata": sorted(
            ({"stratum_id": stratum_ids[signature],
              "signature_sha256": signature,
              "roles": sorted(roles)}
             for signature, roles in strata.items()),
            key=lambda entry: entry["stratum_id"]),
        "role_to_stratum": {
            role: stratum_ids[signature]
            for signature, roles in strata.items() for role in roles},
        "pooling_rule": (
            "A checkpoint whose (bytes, token IDs, common prefix, discriminant "
            "position) tuple differs from the reference in any element is an "
            "isomorphic re-instantiation stratum and is never pooled as the "
            "same frozen byte/token interface."),
        "distinct_stratum_count": len(strata),
    }


