def _encode(tokenizer, text: str):
    COUNTERS["encode_calls"] += 1
    return list(tokenizer(text, add_special_tokens=False)["input_ids"])


def _surface(tokenizer, text: str):
    ids = _encode(tokenizer, text)
    payload = text.encode("utf-8")
    return {
        "text": text,
        "utf8_bytes": len(payload),
        "utf8_sha256": _sha256_bytes(payload),
        "token_ids": ids,
        "token_count": len(ids),
    }


def _common_prefix_length(sequences):
    if not sequences:
        return 0
    shortest = min(len(sequence) for sequence in sequences)
    for index in range(shortest):
        column = {sequence[index] for sequence in sequences}
        if len(column) != 1:
            return index
    return shortest


def probe_checkpoint(role: str, record, cache_root: pathlib.Path):
    """Freeze every byte/token surface for one checkpoint revision."""
    from transformers import AutoTokenizer

    local_dir = record["local_dir"]
    try:
        tokenizer = AutoTokenizer.from_pretrained(
            local_dir, trust_remote_code=False, use_fast=True)
    except Exception as error:
        raise Study3RAcquisitionError(
            "STUDY3R_PROTOCOL_AUTHORING_FAILED_CHECKPOINT_OR_TOKENIZER_UNRESOLVABLE: "
            "%s could not be instantiated with trust_remote_code=False: %s"
            % (record["repository_id"], error))
    COUNTERS["tokenizer_constructions"] += 1

    config = json.loads((pathlib.Path(local_dir) / "config.json").read_text(
        encoding="utf-8"))
    tokenizer_config = json.loads(
        (pathlib.Path(local_dir) / "tokenizer_config.json").read_text(
            encoding="utf-8"))
    generation_config_path = pathlib.Path(local_dir) / "generation_config.json"
    generation_config = (
        json.loads(generation_config_path.read_text(encoding="utf-8"))
        if generation_config_path.exists() else {})

    chat_template = tokenizer_config.get("chat_template")
    if not isinstance(chat_template, str) or not chat_template:
        raise Study3RAcquisitionError(
            "STUDY3R_PROTOCOL_AUTHORING_FAILED_CHECKPOINT_OR_TOKENIZER_UNRESOLVABLE: "
            "%s exposes no chat template" % (record["repository_id"],))

    # Legal E0 answer surfaces.
    answer_surfaces = {label: _surface(tokenizer, label)
                       for label in tasks.LABELS}
    longest_surface_tokens = max(surface["token_count"]
                                 for surface in answer_surfaces.values())
    max_new_tokens = longest_surface_tokens + E0_TERMINATION_MARGIN_TOKENS

    fixture = tasks.canonical_fixture()
    item_body = str(fixture["item_body"])

    # Arm 1: common raw/direct-answer envelope, identical bytes everywhere.
    raw_prompt = tasks.raw_arm_prompt(item_body)

    # Arm 2: checkpoint-revision-specific role-canonical envelope.
    COUNTERS["chat_template_renders"] += 1
    chat_prefix = tokenizer.apply_chat_template(
        [{"role": "user", "content": item_body}],
        tokenize=False, add_generation_prompt=True)
    opened = [marker for marker in REASONING_OPEN_MARKERS
              if chat_prefix.endswith(marker)]
    reasoning_span_opened = bool(opened)
    closure = REASONING_CLOSE_BYTES if reasoning_span_opened else ""
    chat_prompt = chat_prefix + closure + tasks.ANSWER_CUE

    # Canonical generated-CoT route: separate envelope, separate parser.
    COUNTERS["chat_template_renders"] += 1
    cot_prompt = tokenizer.apply_chat_template(
        [{"role": "user", "content": item_body + "\n\n" + COT_INSTRUCTION}],
        tokenize=False, add_generation_prompt=True)

    arms = {}
    for arm_id, prompt in ((RAW_ARM_ID, raw_prompt),
                           (CHAT_ARM_ID, chat_prompt)):
        prompt_surface = _surface(tokenizer, prompt)
        candidates = {}
        full_sequences = []
        for label in tasks.LABELS:
            ids = prompt_surface["token_ids"] + answer_surfaces[label]["token_ids"]
            full_sequences.append(ids)
            candidates[label] = {
                "candidate_text": prompt + label,
                "candidate_token_ids": ids,
                "candidate_token_count": len(ids),
            }
        prefix_length = _common_prefix_length(full_sequences)
        arms[arm_id] = {
            "arm_id": arm_id,
            "prompt": prompt_surface,
            "d0_candidates": candidates,
            "d0_common_prefix_token_length": prefix_length,
            "d0_common_prefix_token_ids":
                full_sequences[0][:prefix_length],
            "d0_discriminant_position": prefix_length,
            "d0_discriminant_token_ids": {
                label: full_sequences[index][prefix_length]
                for index, label in enumerate(tasks.LABELS)
            },
        }

    eos_token = tokenizer_config.get("eos_token")
    if isinstance(eos_token, dict):
        eos_token = eos_token.get("content")

    return {
        "role": role,
        "repository_id": record["repository_id"],
        "immutable_revision": record["immutable_revision"],
        "tokenizer_class": type(tokenizer).__name__,
        "vocab_size_from_config": config.get("vocab_size"),
        "tokenizer_vocab_size": int(tokenizer.vocab_size),
        "max_position_embeddings": config.get("max_position_embeddings"),
        "model_type": config.get("model_type"),
        "trust_remote_code": False,
        "special_tokens": {
            "bos_token": tokenizer.bos_token,
            "bos_token_id": tokenizer.bos_token_id,
            "eos_token": tokenizer.eos_token,
            "eos_token_id": tokenizer.eos_token_id,
            "pad_token": tokenizer.pad_token,
            "pad_token_id": tokenizer.pad_token_id,
            "unk_token": tokenizer.unk_token,
            "tokenizer_config_eos_token": eos_token,
            "generation_config_eos_token_id":
                generation_config.get("eos_token_id"),
            "generation_config_bos_token_id":
                generation_config.get("bos_token_id"),
        },
        "chat_template_sha256": _sha256_text(chat_template),
        "chat_template_bytes": len(chat_template.encode("utf-8")),
        "e0": {
            "legal_answer_surfaces": answer_surfaces,
            "longest_legal_answer_surface_tokens": longest_surface_tokens,
            "termination_margin_tokens": E0_TERMINATION_MARGIN_TOKENS,
            "max_new_tokens": max_new_tokens,
            "add_special_tokens": False,
            "do_sample": False,
        },
        "arms": arms,
        "role_canonical_envelope": {
            "generation_prompt": _surface(tokenizer, chat_prefix),
            "reasoning_span_opened_by_template": reasoning_span_opened,
            "reasoning_open_marker": opened[0] if opened else None,
            "frozen_reasoning_closure": closure,
            "answer_cue": tasks.ANSWER_CUE,
        },
        "cot_route": {
            "route_id": COT_ROUTE_ID,
            "instruction": COT_INSTRUCTION,
            "prompt": _surface(tokenizer, cot_prompt),
            "parser_id": COT_PARSER_ID,
            "parser_regex": COT_PARSER_REGEX,
            "k": 1,
            "do_sample": False,
        },
        "acquired_file_hashes": {entry["path"]: entry["sha256"]
                                 for entry in record["acquired_files"]},
    }


