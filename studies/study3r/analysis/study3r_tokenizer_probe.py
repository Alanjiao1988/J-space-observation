def resolve_and_download(repo_id: str, cache_root: pathlib.Path):
    """Resolve the immutable revision and fetch the allow-listed files only."""
    from huggingface_hub import HfApi, hf_hub_download

    api = HfApi()
    COUNTERS["network_metadata_requests"] += 1
    NETWORK_LOG.append({
        "kind": "metadata",
        "method": "GET",
        "url": "https://huggingface.co/api/models/%s" % repo_id,
    })
    try:
        info = api.model_info(repo_id=repo_id, files_metadata=False)
    except Exception as error:  # pragma: no cover - network failure path
        raise Study3RAcquisitionError(
            "STUDY3R_PROTOCOL_AUTHORING_FAILED_CHECKPOINT_OR_TOKENIZER_UNRESOLVABLE: "
            "%s: %s" % (repo_id, error))
    revision = getattr(info, "sha", None)
    if not revision or len(revision) != 40:
        raise Study3RAcquisitionError(
            "STUDY3R_PROTOCOL_AUTHORING_FAILED_CHECKPOINT_OR_TOKENIZER_UNRESOLVABLE: "
            "%s has no immutable revision" % repo_id)

    repository_paths = sorted(sibling.rfilename for sibling in info.siblings)
    weight_paths = sorted(path for path in repository_paths
                          if path.lower().endswith(WEIGHT_SUFFIXES))

    local_dir = cache_root / repo_id.replace("/", "__") / revision
    local_dir.mkdir(parents=True, exist_ok=True)

    acquired = []
    for relative in DOWNLOAD_ALLOW_LIST:
        if relative not in repository_paths:
            if relative == "generation_config.json":
                continue
            raise Study3RAcquisitionError(
                "STUDY3R_PROTOCOL_AUTHORING_FAILED_CHECKPOINT_OR_TOKENIZER_UNRESOLVABLE: "
                "%s@%s is missing %s" % (repo_id, revision, relative))
        COUNTERS["network_file_downloads"] += 1
        NETWORK_LOG.append({
            "kind": "file",
            "method": "GET",
            "url": "https://huggingface.co/%s/resolve/%s/%s"
                   % (repo_id, revision, relative),
        })
        fetched = hf_hub_download(repo_id=repo_id, filename=relative,
                                  revision=revision,
                                  local_dir=str(local_dir))
        payload = pathlib.Path(fetched).read_bytes()
        if relative.lower().endswith(WEIGHT_SUFFIXES):  # pragma: no cover
            COUNTERS["weight_files_acquired"] += 1
        COUNTERS["files_acquired"] += 1
        acquired.append({
            "path": relative,
            "bytes": len(payload),
            "sha256": _sha256_bytes(payload),
        })

    on_disk = sorted(str(child.relative_to(local_dir)).replace(os.sep, "/")
                     for child in local_dir.rglob("*")
                     if child.is_file() and ".cache" not in child.parts)
    stray = [path for path in on_disk if path.lower().endswith(WEIGHT_SUFFIXES)]
    if stray:  # pragma: no cover - defensive
        raise Study3RAcquisitionError("weight file present on disk: %r" % stray)

    return {
        "repository_id": repo_id,
        "immutable_revision": revision,
        "download_allow_list": list(DOWNLOAD_ALLOW_LIST),
        "acquired_files": acquired,
        "local_paths_on_disk": on_disk,
        "repository_paths_at_revision": repository_paths,
        "weight_paths_present_in_repository": weight_paths,
        "weight_paths_requested": [],
        "weight_bytes_acquired": 0,
        "local_dir": str(local_dir),
    }


