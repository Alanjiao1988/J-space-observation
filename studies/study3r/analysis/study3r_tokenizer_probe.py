def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache-root", required=False,
                        help="directory outside the repository for acquired files")
    parser.add_argument("--out-dir", default=str(ACQUISITION_DIR))
    parser.add_argument("--observation-timestamp", required=False,
                        help="RFC 3339 UTC observation timestamp")
    parser.add_argument("--schemas-only", action="store_true",
                        help="regenerate only the three acquisition schemas; "
                             "performs no network or tokenizer operation")
    args = parser.parse_args(argv)

    out_dir = pathlib.Path(args.out_dir)
    if args.schemas_only:
        write_json(out_dir / "study3r_checkpoint_acquisition_v1.schema.json",
                   acquisition_schema())
        write_json(out_dir / "study3r_tokenizer_surfaces_v1.schema.json",
                   surfaces_schema())
        write_json(out_dir / "study3r_tokenizer_equivalence_v1.schema.json",
                   equivalence_schema())
        print("regenerated 3 acquisition schemas; 0 network requests, "
              "0 tokenizer constructions")
        return 0
    if not args.observation_timestamp:
        parser.error("--observation-timestamp is required for acquisition")

    import huggingface_hub
    import tokenizers
    import transformers

    cache_root = pathlib.Path(args.cache_root)

    records = []
    probes = []
    for role, repo_id in CHECKPOINT_ROLES:
        record = resolve_and_download(repo_id, cache_root)
        record["role"] = role
        records.append(record)
        probes.append(probe_checkpoint(role, record, cache_root))

    acquisition = {
        "schema_version": "study3r-checkpoint-acquisition-v1",
        "authority":
            "studies/study3r/prompts/study3r_protocol_v1_authoring_authority.md",
        "observation_timestamp_utc": args.observation_timestamp,
        "target_checkpoint": TARGET_CHECKPOINT,
        "rp_b_ladder": list(RP_B_LADDER),
        "rp_b_ladder_length": len(RP_B_LADDER),
        "download_allow_list": list(DOWNLOAD_ALLOW_LIST),
        "trust_remote_code": False,
        "checkpoints": [
            {
                "role": record["role"],
                "repository_id": record["repository_id"],
                "immutable_revision": record["immutable_revision"],
                "acquired_files": record["acquired_files"],
                "repository_paths_at_revision":
                    record["repository_paths_at_revision"],
                "weight_paths_present_in_repository":
                    record["weight_paths_present_in_repository"],
                "weight_paths_requested": record["weight_paths_requested"],
                "weight_bytes_acquired": record["weight_bytes_acquired"],
                "local_paths_on_disk": record["local_paths_on_disk"],
            }
            for record in records
        ],
        "no_weight_file_proof": {
            "weight_suffixes_treated_as_weight_bearing": list(WEIGHT_SUFFIXES),
            "weight_paths_requested_total": 0,
            "weight_files_acquired_total": COUNTERS["weight_files_acquired"],
            "weight_bytes_acquired_total": 0,
            "every_acquired_path_is_in_the_allow_list": all(
                entry["path"] in DOWNLOAD_ALLOW_LIST
                for record in records for entry in record["acquired_files"]),
            "no_acquired_path_has_a_weight_suffix": all(
                not entry["path"].lower().endswith(WEIGHT_SUFFIXES)
                for record in records for entry in record["acquired_files"]),
        },
        "library_versions": {
            "python": platform.python_version(),
            "transformers": transformers.__version__,
            "tokenizers": tokenizers.__version__,
            "huggingface_hub": huggingface_hub.__version__,
        },
        "network_requests": NETWORK_LOG,
        "network_request_count": len(NETWORK_LOG),
        "counters": dict(COUNTERS),
    }

    surfaces = {
        "schema_version": "study3r-tokenizer-surfaces-v1",
        "authority":
            "studies/study3r/prompts/study3r_protocol_v1_authoring_authority.md",
        "arm_ids": [RAW_ARM_ID, CHAT_ARM_ID],
        "arm_differentiating_field": ARM_DIFFERENTIATING_FIELD,
        "cot_route_id": COT_ROUTE_ID,
        "label_alphabet": list(tasks.LABELS),
        "item_body_template": tasks.ITEM_BODY_TEMPLATE,
        "answer_cue": tasks.ANSWER_CUE,
        "raw_envelope_separator": tasks.RAW_ENVELOPE_SEPARATOR,
        "canonical_fixture": tasks.canonical_fixture(),
        "tokenizer_fixtures": tasks.tokenizer_fixtures(),
        "checkpoints": probes,
    }

